"""
SymboLM PyTorch Dataset & Collator
==================================
Dataset class and collators for supervised fine-tuning and GRPO RL.
Supports prompt masking (loss calculated only on symbolic trace + answer tokens).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional

import torch
from torch.utils.data import Dataset
from transformers import PreTrainedTokenizerFast, AutoTokenizer


class SymbolicSFTDataset(Dataset):
    """
    Reads JSONL files generated by build_dataset.py.
    Provides tokens with attention_mask and labels (prompt tokens masked with -100).
    """

    def __init__(
        self,
        jsonl_path: str | Path,
        tokenizer: PreTrainedTokenizerFast,
        max_length: int = 1024,
    ):
        self.tokenizer = tokenizer
        self.max_length = max_length
        self.records: List[Dict[str, Any]] = []

        path = Path(jsonl_path)
        if not path.exists():
            raise FileNotFoundError(f"Dataset file not found: {path}")

        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    self.records.append(json.loads(line))

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        item = self.records[idx]
        messages = item["messages"]

        # Formulate prompt vs full text
        prompt_msgs = messages[:-1]
        full_msgs = messages

        # Format using tokenizer's chat template or fallback
        if getattr(self.tokenizer, "chat_template", None):
            prompt_str = self.tokenizer.apply_chat_template(
                prompt_msgs, add_generation_prompt=True, tokenize=False
            )
            full_str = self.tokenizer.apply_chat_template(
                full_msgs, tokenize=False
            )
        else:
            prompt_str = f"<|im_start|>system\n{prompt_msgs[0]['content']}<|im_end|>\n<|im_start|>user\n{prompt_msgs[1]['content']}<|im_end|>\n<|im_start|>assistant\n"
            full_str = f"{prompt_str}{messages[-1]['content']}<|im_end|>\n"

        prompt_encoded = self.tokenizer(
            prompt_str,
            truncation=True,
            max_length=self.max_length,
            add_special_tokens=False,
        )
        full_encoded = self.tokenizer(
            full_str,
            truncation=True,
            max_length=self.max_length,
            add_special_tokens=False,
        )

        input_ids = full_encoded["input_ids"]
        attention_mask = full_encoded["attention_mask"]

        # Mask prompt tokens with -100 in labels so loss only trains completion
        prompt_len = min(len(prompt_encoded["input_ids"]), len(input_ids))
        labels = [-100] * prompt_len + input_ids[prompt_len:]

        return {
            "input_ids": torch.tensor(input_ids, dtype=torch.long),
            "attention_mask": torch.tensor(attention_mask, dtype=torch.long),
            "labels": torch.tensor(labels, dtype=torch.long),
        }


class SymbolicDataCollator:
    """Pads input_ids, attention_mask, and labels to batch max_len.
    On TPU, supports fixed max_length or multiples of 64/128 to prevent XLA dynamic shape recompilation.
    """

    def __init__(
        self,
        pad_token_id: int,
        pad_to_multiple_of: Optional[int] = None,
        max_length: Optional[int] = None,
    ):
        self.pad_token_id = pad_token_id
        self.pad_to_multiple_of = pad_to_multiple_of
        self.max_length = max_length

    def __call__(self, batch: List[Dict[str, torch.Tensor]]) -> Dict[str, torch.Tensor]:
        max_len = max(len(x["input_ids"]) for x in batch)
        if self.pad_to_multiple_of is not None and self.pad_to_multiple_of > 0:
            max_len = ((max_len + self.pad_to_multiple_of - 1) // self.pad_to_multiple_of) * self.pad_to_multiple_of
        if self.max_length is not None:
            max_len = max(max_len, self.max_length)

        batch_input_ids = []
        batch_attention_mask = []
        batch_labels = []

        for item in batch:
            pad_len = max_len - len(item["input_ids"])
            batch_input_ids.append(
                torch.cat([item["input_ids"], torch.full((pad_len,), self.pad_token_id, dtype=torch.long)])
            )
            batch_attention_mask.append(
                torch.cat([item["attention_mask"], torch.zeros(pad_len, dtype=torch.long)])
            )
            batch_labels.append(
                torch.cat([item["labels"], torch.full((pad_len,), -100, dtype=torch.long)])
            )

        return {
            "input_ids": torch.stack(batch_input_ids),
            "attention_mask": torch.stack(batch_attention_mask),
            "labels": torch.stack(batch_labels),
        }
